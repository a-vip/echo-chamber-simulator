/**
 * The Echo Chamber Simulator - Feed Rot Dossier Generator
 * Creates an exportable retro cyber share-card graphic on an HTML5 canvas,
 * with downloadable PNG and one-click clipboard stats summary!
 */

class DossierGenerator {
  constructor() {
    this.canvas = null;
    this.ctx = null;
  }

  generate(simState) {
    if (!this.canvas) {
      this.canvas = document.createElement('canvas');
      this.canvas.width = 640;
      this.canvas.height = 420;
      this.ctx = this.canvas.getContext('2d');
    }

    const ctx = this.ctx;
    const w = this.canvas.width;
    const h = this.canvas.height;

    // Background gradient
    const bgGrad = ctx.createLinearGradient(0, 0, w, h);
    bgGrad.addColorStop(0, '#09090b');
    bgGrad.addColorStop(1, '#18181b');
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, w, h);

    // Neon Cyber Border
    ctx.strokeStyle = '#f59e0b';
    ctx.lineWidth = 3;
    ctx.strokeRect(10, 10, w - 20, h - 20);

    ctx.strokeStyle = '#3b82f6';
    ctx.lineWidth = 1;
    ctx.strokeRect(14, 14, w - 28, h - 28);

    // Header Title
    ctx.fillStyle = '#f59e0b';
    ctx.font = 'bold 20px monospace';
    ctx.fillText('⚡ THE ECHO CHAMBER SIMULATOR', 30, 48);

    ctx.fillStyle = '#a1a1aa';
    ctx.font = '12px monospace';
    ctx.fillText('OFFICIAL ALGORITHMIC DISGRACE & ROT DOSSIER', 30, 68);

    // Divider Line
    ctx.strokeStyle = '#27272a';
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(30, 80);
    ctx.lineTo(w - 30, 80);
    ctx.stroke();

    // Determine Architectural Title Rank
    let rank = 'NOVICE ALGORITHMIC PROVOCATEUR';
    if (simState.watts > 100000) rank = 'CERTIFIED RAGEBAIT OLIGARCH (CLASS 3)';
    if (simState.watts > 500000) rank = 'SUPREME ARCHITECT OF SOCIETAL COLLAPSE';
    if (window.AchievementSystem && window.AchievementSystem.prestigeLevel > 0) {
      rank = `TRANSCENDENT TIMELINE REBOOTER (PRESTIGE ${window.AchievementSystem.prestigeLevel})`;
    }

    ctx.fillStyle = '#ef4444';
    ctx.font = 'bold 13px monospace';
    ctx.fillText(`OPERATOR RANK: ${rank}`, 30, 108);

    // Grid of Statistics Badges
    const stats = [
      { label: 'HARVESTED NEURO-WATTS', val: `${Math.floor(simState.watts).toLocaleString()} ⚡`, color: '#fbbf24' },
      { label: 'AD MONETIZATION CASH', val: `$${Math.floor(simState.cash).toLocaleString()} 💵`, color: '#4ade80' },
      { label: 'GOLDILOCKS ROT STREAK', val: `${Math.floor(simState.rotZoneStreakSec)}s (5.0x Multiplier)`, color: '#f97316' },
      { label: 'PEAK SERVER HEAT', val: `${simState.serverTemp.toFixed(1)}°C / ${simState.maxServerTemp}°C`, color: '#38bdf8' },
      { label: 'SIMULATION TIME', val: `DAY ${simState.day} (${Math.floor(simState.gameTimeSec)}s active)`, color: '#c084fc' },
      { label: 'CIVILIZATION TENSION', val: `${simState.tension.toFixed(1)}%`, color: simState.tension >= 65 ? '#f87171' : '#34d399' }
    ];

    const boxW = 270;
    const boxH = 50;

    stats.forEach((st, i) => {
      const col = i % 2;
      const row = Math.floor(i / 2);
      const bx = 30 + col * (boxW + 35);
      const by = 130 + row * (boxH + 15);

      // Card Box
      ctx.fillStyle = '#111827';
      ctx.fillRect(bx, by, boxW, boxH);
      ctx.strokeStyle = '#374151';
      ctx.lineWidth = 1;
      ctx.strokeRect(bx, by, boxW, boxH);

      // Label
      ctx.fillStyle = '#9ca3af';
      ctx.font = '10px monospace';
      ctx.fillText(st.label, bx + 10, by + 18);

      // Value
      ctx.fillStyle = st.color;
      ctx.font = 'bold 15px monospace';
      ctx.fillText(st.val, bx + 10, by + 40);
    });

    // Apocalypse Badges Awarded
    let endingsCount = 0;
    if (window.AchievementSystem) {
      endingsCount = Object.keys(window.AchievementSystem.endingsUnlocked).length;
    }

    ctx.fillStyle = '#e2e8f0';
    ctx.font = '11px monospace';
    ctx.fillText(`APOCALYPSE MILESTONES DISCOVERED: ${endingsCount} / 5`, 30, 350);

    // Footer Watermark
    ctx.fillStyle = '#64748b';
    ctx.font = '10px monospace';
    ctx.fillText('Generated by The Echo Chamber Simulator • github.com/a-vip/echo-chamber-simulator', 30, 390);

    return this.canvas;
  }

  downloadPNG(simState) {
    const canvas = this.generate(simState);
    const link = document.createElement('a');
    link.download = `echo-chamber-dossier-day${simState.day}.png`;
    link.href = canvas.toDataURL('image/png');
    link.click();
    if (window.AudioSynth) window.AudioSynth.playCashChime();
  }

  copyShareText(simState) {
    const text = `⚡ The Echo Chamber Simulator (Real-Time Feed Rot)
📊 Day ${simState.day} Report:
- Harvested: ${Math.floor(simState.watts).toLocaleString()} Neuro-Watts ⚡
- Ad Cash: $${Math.floor(simState.cash).toLocaleString()} 💵
- Tension: ${simState.tension.toFixed(1)}% | Server Temp: ${simState.serverTemp.toFixed(1)}°C
- Goldilocks Rot Streak: ${Math.floor(simState.rotZoneStreakSec)}s (5x Multiplier)

Try managing the unhinged human algorithm yourself:
https://a-vip.github.io/echo-chamber-simulator/`;

    navigator.clipboard.writeText(text).then(() => {
      if (window.AudioSynth) window.AudioSynth.playClick();
    });
    return text;
  }
}

window.DossierGenerator = new DossierGenerator();

